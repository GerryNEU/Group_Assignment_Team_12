    private FacultyProfile safeFacultyOf(CourseOffer co) {
    try {
        return co.getFacultyProfile();   // this may NPE if no assignment in current CourseOffer impl
    } catch (Exception ex) {
        return null;
    }
}
    private void populateTable() {
        DefaultTableModel dtm = (DefaultTableModel) tableCourse.getModel();
        dtm.setRowCount(0);

        Department dept = business.getDepartment();
        CourseSchedule cs = dept.getCourseSchedule("Fall 2025");  // change semester if needed
        if (cs == null) return;

        List<CourseOffer> offers = cs.getSchedule();
        for (CourseOffer co : offers) {
            String courseName = co.getSubjectCourse().getName();  

            // Faculty: use safe wrapper to avoid NPE from CourseOffer.getFacultyProfile()
            info5100.university.example.Persona.Faculty.FacultyProfile fp = safeFacultyOf(co);
            String facultyName = (fp == null) ? "Unassigned" : fp.getPerson().getName();

            Object[] row = new Object[]{
                co.getCourseNumber(),
                courseName,
                co.getSeatCount(),
                co.getEnrolledCount(),
                facultyName,
                co.getScheduleTime(),    
            };
            dtm.addRow(row);
        }
    }
