    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        int selectedRow = tableStudentList.getSelectedRow();
        if (selectedRow < 0) {
            JOptionPane.showMessageDialog(this, "Please select a student first.");
            return;
        }

        if (selectedCourse == null) {
            JOptionPane.showMessageDialog(this, "Please select a course first.");
            return;
        }

        try {
            double grade = Double.parseDouble(fieldGrade.getText().trim());
            if (grade < 0 || grade > 100) {
                JOptionPane.showMessageDialog(this, "Please enter a score between 0 and 100.");
                return;
            }
            String studentId = (String) tableStudentList.getValueAt(selectedRow, 0);

            boolean updated = false;
            for (SeatAssignment sa : selectedCourse.getSeatAssignments()) {
                StudentProfile ssp = sa.getStudentProfile();
                if (ssp != null && ssp.getPerson() != null 
                    && ssp.getPerson().getPersonId().equals(studentId)) {
                    sa.setGrade(grade);  
                    updated = true;
                    break;
                }
            }
            if (!updated) {
                JOptionPane.showMessageDialog(this, "Update failed: student not found in this course.");
                return;
            }
            populateStudentTable();
            fieldGrade.setText("");
            JOptionPane.showMessageDialog(this, "Grade updated successfully.");
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Invalid grade input.");
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

