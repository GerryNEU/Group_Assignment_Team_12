    private void btnViewActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewActionPerformed
        // TODO add your handling code here:
        int selectedRow = tableStudentList.getSelectedRow();
        if (selectedRow < 0) {
            JOptionPane.showMessageDialog(this, "Please select a student first.");
            return;
        }
        String studentId = (String) tableStudentList.getValueAt(selectedRow, 0);
        StudentProfile sp = null;
        for (SeatAssignment sa : selectedCourse.getSeatAssignments()) {
            if (sa.getStudentProfile().getPerson().getPersonId().equals(studentId)) {
                sp = sa.getStudentProfile();
                break;
            }
        }
        if (sp != null) {
            ViewTranscriptJPanel panel = new ViewTranscriptJPanel(sp);
            JOptionPane.showMessageDialog(this, panel, 
                "Transcript Summary for " + sp.getPerson().getName(), JOptionPane.PLAIN_MESSAGE);
        }
    }//GEN-LAST:event_btnViewActionPerformed


