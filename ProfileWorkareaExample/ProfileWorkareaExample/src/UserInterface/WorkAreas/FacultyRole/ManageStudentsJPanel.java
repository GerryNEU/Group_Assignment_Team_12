    private void populateStudentTable() {
        DefaultTableModel model = new DefaultTableModel(
            new Object[]{"Student ID", "Name", "Score (0-100)", "GPA", "Letter"}, 0);
        tableStudentList.setModel(model);
        model.setRowCount(0);

        if (selectedCourse == null) return;

        ArrayList<SeatAssignment> seatList = selectedCourse.getSeatAssignments();
        for (SeatAssignment sa : seatList) {
            StudentProfile sp = sa.getStudentProfile();
            if (sp == null || sp.getPerson() == null) continue;

            Object[] row = new Object[5];
            row[0] = sp.getPerson().getPersonId();
            row[1] = sp.getPerson().getName();
            row[2] = sa.getRawScore();
            row[3] = sa.getGrade();        
            model.addRow(row);
        }
    }
    private void rankStudents() {
    if (selectedCourse == null) {
        JOptionPane.showMessageDialog(this, "Please select a course first.");
        return;
    }
    ArrayList<SeatAssignment> seatList = selectedCourse.getSeatAssignments();
    seatList.sort(Comparator.comparingDouble(SeatAssignment::getGrade).reversed());

    double total = 0;
    for (SeatAssignment sa : seatList) total += sa.getGrade();
    double avg = seatList.isEmpty() ? 0 : total / seatList.size();

    // 用排序后的 seatList 重绘表格（与上面 populateStudentTable 的5列保持一致）
    DefaultTableModel model = (DefaultTableModel) tableStudentList.getModel();
    model.setRowCount(0);
    for (SeatAssignment sa : seatList) {
        StudentProfile sp = sa.getStudentProfile();
        if (sp == null || sp.getPerson() == null) continue;
        Object[] row = new Object[5];
        row[0] = sp.getPerson().getPersonId();
        row[1] = sp.getPerson().getName();
        row[2] = sa.getRawScore();
        row[3] = sa.getGrade();
        row[4] = sa.getLetterGrade();
        model.addRow(row);
    }
    lblGPA.setText(String.format("Class GPA: %.2f", avg));
}


