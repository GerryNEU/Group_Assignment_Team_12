    // Method to fill the faculty dropdown
    private void populateFacultyCombo() {
        DefaultComboBoxModel<FacultyProfile> model = new DefaultComboBoxModel<>();
        Department department = business.getDepartment();
        FacultyDirectory facultyDirectory = department.getFacultyDirectory();
        ArrayList<FacultyProfile> faculties = facultyDirectory.getTeacherList();

        model.addElement(null); // Add a null option for "Unassigned"

        for (FacultyProfile faculty : faculties) {
            model.addElement(faculty); // Add the FacultyProfile object
        }
        comboFaculty.setModel(model);
        comboFaculty.setRenderer(new javax.swing.DefaultListCellRenderer() {
             @Override
             public java.awt.Component getListCellRendererComponent(javax.swing.JList<?> list, Object value, int index, boolean isSelected, boolean cellHasFocus) {
                 super.getListCellRendererComponent(list, value, index, isSelected, cellHasFocus);
                 if (value instanceof FacultyProfile) {
                     FacultyProfile faculty = (FacultyProfile) value;
                     Person person = faculty.getPerson();
                     if (person != null) {
                         setText(person.getName());
                     } else {
                         setText("Unknown Faculty");
                     }
                 } else {
                     setText("Select Faculty (Optional)");
                 }
                 return this;
             }
        });
    }
    
    
    // Method to populate the form fields with data from the CourseOffer being edited
    private void populateFields() {
        if (courseOfferToEdit == null) {
            return; 
        }

        Course course = courseOfferToEdit.getSubjectCourse();
        lblCourseNumber.setText(course.getCourseNumber());
        lblCourseName.setText(course.getName());

        txtCapacity.setText(String.valueOf(courseOfferToEdit.getSeatCount()));
        txtSchedule.setText(courseOfferToEdit.getScheduleTime());

        txtRoom.setText("To be Added"); 

        // Select the currently assigned faculty in the dropdown
        FacultyProfile currentFaculty = courseOfferToEdit.getFacultyProfile();
        comboFaculty.setSelectedItem(currentFaculty); 
    }
    
