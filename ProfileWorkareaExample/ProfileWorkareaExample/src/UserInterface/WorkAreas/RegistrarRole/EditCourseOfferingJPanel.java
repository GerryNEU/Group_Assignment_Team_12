    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        // --- 1. Get User Input ---
        FacultyProfile selectedFaculty = (FacultyProfile) comboFaculty.getSelectedItem();
        String capacityStr = txtCapacity.getText().trim();
        String scheduleStr = txtSchedule.getText().trim();
        String roomStr = txtRoom.getText().trim();

        // --- 2. Input Validation ---
        int capacity;
        try {
            capacity = Integer.parseInt(capacityStr);
            if (capacity <= 0) {
                JOptionPane.showMessageDialog(this, "Capacity must be a positive number.", "Input Error", JOptionPane.WARNING_MESSAGE);
                return;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter a valid number for capacity.", "Input Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Add more validation if needed
         if (scheduleStr.isEmpty()) {
             JOptionPane.showMessageDialog(this, "Please enter a schedule.", "Input Error", JOptionPane.WARNING_MESSAGE);
            return;
        }
         if (roomStr.isEmpty()) {
             JOptionPane.showMessageDialog(this, "Please enter a room.", "Input Error", JOptionPane.WARNING_MESSAGE);
            return;
        }


        // --- 3. Update Course Offering Object ---
        // The object 'courseOfferToEdit' already holds the CourseOffer we want to modify

        // Update Faculty
        courseOfferToEdit.assignFaculty(selectedFaculty); // assignFaculty handles null internally perhaps, or check here

        // Update Capacity 
        if (capacity != courseOfferToEdit.getSeatCount()) {
             courseOfferToEdit.getSeatList().clear(); // Clear old seats first
             courseOfferToEdit.generatSeats(capacity);
             System.out.println("Warning: Seats regenerated, existing assignments might be lost."); // Add a log or user warning
        }


        // Update Schedule
        courseOfferToEdit.setScheduleTime(scheduleStr);

        // Update Room (Requires setRoom in CourseOffer.java)
        // courseOfferToEdit.setRoom(roomStr);

        // --- 4. Confirmation and Navigation ---
        JOptionPane.showMessageDialog(this, "Course Offering updated successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);

        // Refresh the table in the previous panel
        manageCourseOfferingsPanel.populateTable();

        // Go back to the previous panel
        CardSequencePanel.remove(this);
        java.awt.CardLayout layout = (java.awt.CardLayout) CardSequencePanel.getLayout();
        layout.previous(CardSequencePanel);
    }//GEN-LAST:event_btnSaveActionPerformed

