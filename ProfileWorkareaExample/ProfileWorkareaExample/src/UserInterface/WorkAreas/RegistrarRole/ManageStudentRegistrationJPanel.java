    private void btnEnrollActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEnrollActionPerformed
        // TODO add your handling code here:
        // --- 1. Get Selected Student ---
        int selectedStudentRow = tblStudents.getSelectedRow();
        if (selectedStudentRow < 0) {
            JOptionPane.showMessageDialog(this, "Please select a student.", "Selection Required", JOptionPane.WARNING_MESSAGE);
            return;
        }
        // Assuming Student ID is in column 0
        String selectedStudentId = (String) tblStudents.getValueAt(selectedStudentRow, 0);
        Department department = business.getDepartment();
        StudentProfile selectedStudent = department.getStudentDirectory().findStudent(selectedStudentId);
        if (selectedStudent == null) {
            JOptionPane.showMessageDialog(this, "Could not find the selected student profile.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // --- 2. Get Selected Course Offering ---
        int selectedCourseRow = tblCourseOfferings.getSelectedRow();
        if (selectedCourseRow < 0) {
            JOptionPane.showMessageDialog(this, "Please select a course offering.", "Selection Required", JOptionPane.WARNING_MESSAGE);
            return;
        }
        // Assuming Course Number is in column 0
        String selectedCourseNumber = (String) tblCourseOfferings.getValueAt(selectedCourseRow, 0);
        CourseSchedule courseSchedule = department.getCourseSchedule("Fall 2025"); // Assuming Fall 2025
        if (courseSchedule == null) {
            JOptionPane.showMessageDialog(this, "Course schedule not found.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        CourseOffer selectedCourseOffer = courseSchedule.getCourseOfferByNumber(selectedCourseNumber);
        if (selectedCourseOffer == null) {
            JOptionPane.showMessageDialog(this, "Could not find the selected course offering.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // --- 3. Perform Validations ---

        // Check if course is full
        if (selectedCourseOffer.getEmptySeat() == null) {
            JOptionPane.showMessageDialog(this, "Cannot enroll: Course '" + selectedCourseNumber + "' is full.", "Enrollment Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Get student's current courseload for the semester
        // Assuming Transcript has a method to get or create CourseLoad for a semester
        Transcript transcript = selectedStudent.getTranscript();
        CourseLoad currentLoad = transcript.getCourseLoadBySemester("Fall 2025");
        // If student has no load for this semester yet, create one
        if (currentLoad == null) {
            currentLoad = transcript.newCourseLoad("Fall 2025");
        }

        // Check if student is already enrolled in this course
        ArrayList<SeatAssignment> currentAssignments = currentLoad.getSeatAssignments();
        for (SeatAssignment sa : currentAssignments) {
            if (sa.getCourseOffer() == selectedCourseOffer) {
                 JOptionPane.showMessageDialog(this, "Student is already enrolled in " + selectedCourseNumber + ".", "Enrollment Error", JOptionPane.WARNING_MESSAGE);
                 return;
            }
        }

        // Check credit hour limit (8 credits as per requirements )
        int currentCredits = 0;
        for (SeatAssignment sa : currentAssignments) {
            currentCredits += sa.getCreditHours();
        }
        int courseCredits = selectedCourseOffer.getCreditHours();
        if (currentCredits + courseCredits > 8) {
            JOptionPane.showMessageDialog(this, "Cannot enroll: Exceeds maximum credit hours (8) for the semester. Current credits: " + currentCredits, "Enrollment Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // --- 4. Enroll Student ---
        // The assignEmptySeat method handles finding a seat and creating the SeatAssignment
        SeatAssignment newAssignment = selectedCourseOffer.assignEmptySeat(currentLoad);

        // --- 5. Feedback and Refresh ---
        if (newAssignment != null) {
            JOptionPane.showMessageDialog(this, "Student '" + selectedStudent.getPerson().getName() + "' successfully enrolled in " + selectedCourseNumber + ".", "Enrollment Successful", JOptionPane.INFORMATION_MESSAGE);
            // Refresh the course offering table to show updated enrollment count
            populateCourseOfferingTable();
        } else {
            // This case might occur if getEmptySeat() check fails due to race condition, though unlikely here.
            JOptionPane.showMessageDialog(this, "Failed to enroll student. The course might have become full.", "Enrollment Error", JOptionPane.ERROR_MESSAGE);
            populateCourseOfferingTable(); // Refresh anyway
        }
    }//GEN-LAST:event_btnEnrollActionPerformed

    private void btnDropActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDropActionPerformed
        // TODO add your handling code here:
        // --- 1. Get Selected Student ---
        int selectedStudentRow = tblStudents.getSelectedRow();
        if (selectedStudentRow < 0) {
            JOptionPane.showMessageDialog(this, "Please select a student.", "Selection Required", JOptionPane.WARNING_MESSAGE);
            return;
        }
        String selectedStudentId = (String) tblStudents.getValueAt(selectedStudentRow, 0);
        Department department = business.getDepartment();
        StudentProfile selectedStudent = department.getStudentDirectory().findStudent(selectedStudentId);
        if (selectedStudent == null) {
            JOptionPane.showMessageDialog(this, "Could not find the selected student profile.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // --- 2. Get Selected Course Offering ---
        int selectedCourseRow = tblCourseOfferings.getSelectedRow();
        if (selectedCourseRow < 0) {
            JOptionPane.showMessageDialog(this, "Please select the course offering to drop the student from.", "Selection Required", JOptionPane.WARNING_MESSAGE);
            return;
        }
        String selectedCourseNumber = (String) tblCourseOfferings.getValueAt(selectedCourseRow, 0);
        CourseSchedule courseSchedule = department.getCourseSchedule("Fall 2025"); // Assuming Fall 2025
        if (courseSchedule == null) {
            JOptionPane.showMessageDialog(this, "Course schedule not found.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        CourseOffer selectedCourseOffer = courseSchedule.getCourseOfferByNumber(selectedCourseNumber);
        if (selectedCourseOffer == null) {
            JOptionPane.showMessageDialog(this, "Could not find the selected course offering.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // --- 3. Find the Student's Seat Assignment for this Course ---
        Transcript transcript = selectedStudent.getTranscript();
        CourseLoad currentLoad = transcript.getCourseLoadBySemester("Fall 2025");
        SeatAssignment assignmentToDrop = null;

        if (currentLoad != null) {
            // Iterate through the student's assignments in the current semester
            for (SeatAssignment sa : currentLoad.getSeatAssignments()) {
                // Check if the assignment belongs to the selected CourseOffer
                if (sa.getCourseOffer() == selectedCourseOffer) {
                    assignmentToDrop = sa;
                    break; // Found the assignment
                }
            }
        }

        // --- 4. Validation: Check if student is actually enrolled ---
        if (assignmentToDrop == null) {
            JOptionPane.showMessageDialog(this, "Student '" + selectedStudent.getPerson().getName() + "' is not enrolled in " + selectedCourseNumber + ".", "Drop Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // --- 5. Confirmation Dialog ---
         int confirmation = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to drop student '" + selectedStudent.getPerson().getName() + "' from " + selectedCourseNumber + "?",
            "Confirm Drop",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.WARNING_MESSAGE
        );

        // --- 6. Drop Student if Confirmed ---
        if (confirmation == JOptionPane.YES_OPTION) {
            // Remove the SeatAssignment from the student's CourseLoad
            boolean removedFromLoad = currentLoad.getSeatAssignments().remove(assignmentToDrop);

            // Mark the Seat in the CourseOffer as unoccupied
            Seat seat = assignmentToDrop.getSeat(); // Get the associated Seat
            boolean seatFreed = false;
            if (seat != null) {
                seat.unassignSeat(); // Call the new method to properly unassign
                seatFreed = !seat.isOccupied();
            }

            // --- 7. Feedback and Refresh ---
            if (removedFromLoad && seatFreed) {
                JOptionPane.showMessageDialog(this, "Student dropped successfully.", "Success", JOptionPane.INFORMATION_MESSAGE);
                // Refresh the course offering table
                populateCourseOfferingTable();
            } else {
                 JOptionPane.showMessageDialog(this, "Failed to drop student. Could not update records.", "Error", JOptionPane.ERROR_MESSAGE);
                 // Refresh tables anyway to ensure consistency
                 populateCourseOfferingTable();
            }
        }
        // If user chose NO, do nothing.
    }//GEN-LAST:event_btnDropActionPerformed


