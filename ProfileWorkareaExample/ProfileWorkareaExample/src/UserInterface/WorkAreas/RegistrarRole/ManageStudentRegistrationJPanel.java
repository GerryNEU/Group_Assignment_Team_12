    private void populateStudentTable() {
        DefaultTableModel model = (DefaultTableModel) tblStudents.getModel();
        model.setRowCount(0); // Clear existing data

        Department department = business.getDepartment();
        StudentDirectory studentDirectory = department.getStudentDirectory();

        // Check if studentDirectory or studentlist is null before iterating
        if (studentDirectory != null && studentDirectory.getStudentlist() != null) {
            for (StudentProfile student : studentDirectory.getStudentlist()) {
                Person person = student.getPerson();
                if (person != null) {
                    Object[] row = new Object[2]; // Adjust size based on columns
                    row[0] = person.getPersonId(); // Column 0: Student ID
                    row[1] = person.getName();    // Column 1: Student Name
                    model.addRow(row);
                }
            }
        } else {
             System.err.println("Student directory or list is null.");
             // Optionally show an error message to the user
        }
    }
    
    private void populateCourseOfferingTable() {
    DefaultTableModel model = (DefaultTableModel) tblCourseOfferings.getModel();
        model.setRowCount(0); // Clear existing data

        Department department = business.getDepartment();
        CourseSchedule courseSchedule = department.getCourseSchedule("Fall 2025"); // Assuming Fall 2025

        if (courseSchedule == null) {
            System.err.println("Course schedule for Fall 2025 not found.");
            return;
        }

        ArrayList<CourseOffer> courseOffers = courseSchedule.getSchedule();

        for (CourseOffer co : courseOffers) {
            FacultyProfile faculty = co.getFacultyProfile();
            String facultyName = (faculty != null && faculty.getPerson() != null) ? faculty.getPerson().getName() : "Unassigned";

            Object[] row = new Object[4]; // Adjust size based on columns
            row[0] = co.getCourseNumber();                             // Course Number
            row[1] = co.getSubjectCourse().getName();                 // Course Name
            row[2] = facultyName;                                     // Faculty
            row[3] = co.getEnrolledCount() + "/" + co.getSeatCount(); // Enrolled/Capacity
            model.addRow(row);
        }
    }
    
    
